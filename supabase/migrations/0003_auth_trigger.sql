-- Création automatique du profil à l'inscription d'un utilisateur Supabase Auth.
-- Les métadonnées (first_name, last_name, role) sont fournies à la création du
-- compte (supabase.auth.admin.createUser ou signUp avec options.data).

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, first_name, last_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'first_name', ''),
    coalesce(new.raw_user_meta_data ->> 'last_name', ''),
    coalesce((new.raw_user_meta_data ->> 'role')::app_role, 'assistant')
  );
  return new;
end;
$$;

create or replace trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();
